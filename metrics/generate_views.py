"""Generate the semantic layer from the metric registry (task 1.23).

Usage: ``uv run python -m metrics.generate_views`` (also run by every snapshot build)

Writes one dbt view per file into ``transform/models/semantic/`` (files are ``sem_<view>.sql``
with a dbt alias, because model names must be unique and marts already use names such as
``games``; the views are ``semantic.<view>``) and the view allowlist the SQL
fallback enforces (``transform/semantic_allowlist.txt``). Metric columns come only from
``metrics/registry.yaml``: each metric's aggregate ``sql`` (after its optional ``filter``) is
evaluated over its base rows, grouped by the keys of each grain the metric allows. Adding a metric
is one YAML entry; its column appears in every view for its grains.

The generated files are committed. ``tests/test_semantic_views.py`` fails if they drift from the
registry.
"""

