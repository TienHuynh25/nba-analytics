def metric_cte(m: Metric, src: Source, idx: int) -> str:
    keys = ", ".join(src.keys)
    where = f"\n    where {m.filter}" if m.filter else ""
    return (
        f"m{idx} as (\n    -- {m.name}: {m.formula}\n"
        f"    select {keys}, {m.sql} as {m.name}\n"
        f"    from {{{{ {src.relation} }}}}{where}\n    group by {keys}\n)"
    )


def metric_view(reg: Registry, grain: Grain) -> str:
    _, spine_sql, keys = SPINES[grain]
    metrics = [m for m in reg.metrics if grain in m.grains]
    ctes = [f"spine as (\n{spine_sql}\n)"]
    joins = []
    cols = []
    for i, m in enumerate(metrics):
        src = SOURCES.get((m.base, grain))
        if src is None:
            raise ValueError(f"{m.name}: no source for base {m.base} at grain {grain}")
        ctes.append(metric_cte(m, src, i))
        # Metrics whose base has fewer keys (e.g. awards per player) join on the shared keys.
        on = " and ".join(f"m{i}.{k} = spine.{k}" for k in src.keys if k in keys)
        if grain == Grain.player_career and src.keys == ("player_id",):
            on += " and spine.season_type = 'Regular Season'"
        joins.append(f"left join m{i} on {on}")
        cols.append(f"    m{i}.{m.name}")
    body = (
        f"{HEADER}-- One row per ({', '.join(keys)}). Registry {reg.version}.\n"
        f"with {',\n'.join(ctes)}\n"
        f"select\n    spine.*,\n{',\n'.join(cols)}\nfrom spine\n" + "\n".join(joins) + "\n"
    )
    return body


def registry_info(reg: Registry) -> str:
    return (
        f"{HEADER}select '{reg.version}' as registry_version, {len(reg.metrics)} as metric_count\n"
    )


def _with_alias(view: str, sql: str) -> str:
    return sql.replace(HEADER, f"{HEADER}{{{{ config(alias='{view}') }}}}\n", 1)


def render(reg: Registry) -> dict[str, str]:
    """Map of file name (``sem_<view>.sql``) to SQL."""
    views: dict[str, str] = {}
    for view, sql in PASSTHROUGH.items():
        views[view] = f"{HEADER}{sql}\n"
    for grain in SPINES:
        views[SPINES[grain][0]] = metric_view(reg, grain)
    views["registry_info"] = registry_info(reg)
    return {f"sem_{v}.sql": _with_alias(v, sql) for v, sql in views.items()}


def allowlist(files: Iterable[str]) -> str:
    names = sorted(f.removesuffix(".sql").removeprefix("sem_") for f in files)
    return (
        "# Semantic-layer views the SQL fallback may read (task 1.23 -> 3.16). Generated.\n"
        + "\n".join(f"semantic.{n}" for n in names)
        + "\n"
    )


def write(reg: Registry | None = None, out_dir: Path = OUT_DIR, allow: Path = ALLOWLIST) -> None:
    reg = reg or load()
    files = render(reg)
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.sql"):
        if old.name not in files:
            old.unlink()
    for fname, sql in files.items():
        (out_dir / fname).write_text(sql)
    allow.write_text(allowlist(files))


if __name__ == "__main__":
    write()
